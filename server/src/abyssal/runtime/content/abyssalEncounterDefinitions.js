function resolveAbyssalEncounterVariety(weatherType, overrides = {}) {
  const normalizedWeatherType = String(weatherType || "").trim().toLowerCase() || "unknown";
  const variety =
    ABYSSAL_ENCOUNTER_VARIETY_BY_WEATHER_TYPE[normalizedWeatherType] ||
    ABYSSAL_ENCOUNTER_VARIETY_BY_WEATHER_TYPE.unknown;
  const requestedProfileID = String(
    overrides.profileQuery || variety.preferredProfileID || ABYSSAL_EXPLICIT_PLACEHOLDER_NPC_PROFILE_ID,
  ).trim();
  const npcProfile = resolveSafeAbyssalNpcCatalogEntry(requestedProfileID);
  return {
    ...cloneValue(variety),
    ...npcProfile,
    factionTheme: String(overrides.factionTheme || npcProfile.factionTheme || variety.factionTheme || "guristas"),
  };
}

function resolveAbyssalEncounterTierBand(tier) {
  const normalizedTier = Math.max(0, Math.min(6, toInteger(tier, 1)));
  return cloneValue(
    ABYSSAL_ENCOUNTER_TIER_BANDS.find((entry) =>
      normalizedTier >= entry.minTier && normalizedTier <= entry.maxTier
    ) || ABYSSAL_ENCOUNTER_TIER_BANDS[0]
  );
}

function resolveAbyssalEncounterArchetypeSpec(weatherType, roomIndex) {
  const normalizedWeatherType = String(weatherType || "").trim().toLowerCase() || "unknown";
  const weatherSpec =
    ABYSSAL_ENCOUNTER_ARCHETYPE_SPECS_BY_WEATHER_TYPE[normalizedWeatherType] ||
    ABYSSAL_ENCOUNTER_ARCHETYPE_SPECS_BY_WEATHER_TYPE.unknown;
  const resolvedRoomIndex = Math.max(1, Math.min(3, toInteger(roomIndex, 1)));
  return cloneValue(
    weatherSpec.roomSpecsByIndex[String(resolvedRoomIndex)] ||
    weatherSpec.roomSpecsByIndex[resolvedRoomIndex] ||
    ABYSSAL_ENCOUNTER_ARCHETYPE_SPECS_BY_WEATHER_TYPE.unknown.roomSpecsByIndex[resolvedRoomIndex] ||
    ABYSSAL_ENCOUNTER_ARCHETYPE_SPECS_BY_WEATHER_TYPE.unknown.roomSpecsByIndex[1]
  );
}

